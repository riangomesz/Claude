const cache = new Map();

export function icon(name, size = 18, label) {
  const key = `${name}:${size}`;
  if (!cache.has(key)) {
    const t = document.createElement("template");
    t.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round">${P[name] || P.sparkle}</svg>`;
    cache.set(key, t.content.firstChild);
  }
  const svg = cache.get(key).cloneNode(true);
  if (label) {
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", label);
  } else {
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
  }
  return svg;
}
